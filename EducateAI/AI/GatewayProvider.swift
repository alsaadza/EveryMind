import Foundation

/// Talks to OCI Generative AI through the EducateAI privacy gateway (gateway/server.py).
/// The gateway holds OCI credentials, so no cloud keys live on the iPad. Text is
/// scrubbed of personal details on device first, and again by the gateway.
struct GatewayProvider: AIProvider {
    var baseURL: URL
    var token: String?
    var modelLabel: String

    var displayName: String { "OCI Generative AI (\(modelLabel))" }
    var runsOnDevice: Bool { false }

    struct Msg: Codable { var role: String; var content: String }
    struct ChatBody: Codable {
        var system: String; var messages: [Msg]; var max_tokens: Int; var temperature: Double; var json: Bool; var purpose: String
    }
    struct ChatResponse: Codable { var text: String; var model: String?; var provider: String?; var redactions: Int? }

    func chat(system: String, messages: [Msg], purpose: String, json: Bool, maxTokens: Int = 1200, temperature: Double = 0.4) async throws -> String {
        var req = URLRequest(url: baseURL.appendingPathComponent("v1/chat"))
        req.httpMethod = "POST"
        req.timeoutInterval = ["course", "assignment", "feedback"].contains(purpose) ? 120 : 45
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        if let token, !token.isEmpty { req.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization") }
        let scrubbed = messages.map { Msg(role: $0.role, content: PrivacyFilter.scrub($0.content).text) }
        req.httpBody = try JSONEncoder().encode(ChatBody(system: system, messages: scrubbed, max_tokens: maxTokens, temperature: temperature, json: json, purpose: purpose))
        let (data, resp) = try await URLSession.shared.data(for: req)
        guard let http = resp as? HTTPURLResponse else { throw AIError.badResponse("no response") }
        guard http.statusCode == 200 else {
            let msg = (try? JSONDecoder().decode([String: String].self, from: data))?["error"] ?? "HTTP \(http.statusCode)"
            throw AIError.badResponse(msg)
        }
        return try JSONDecoder().decode(ChatResponse.self, from: data).text
    }

    func health() async throws -> String {
        var req = URLRequest(url: baseURL.appendingPathComponent("health"))
        req.timeoutInterval = 8
        let (data, _) = try await URLSession.shared.data(for: req)
        let obj = try JSONSerialization.jsonObject(with: data) as? [String: Any]
        return "Connected · mode \(obj?["mode"] as? String ?? "?") · model \(obj?["model"] as? String ?? "?")"
    }

    func decode<T: Decodable>(_ type: T.Type, from text: String) throws -> T {
        guard let json = text.extractedJSON, let data = json.data(using: .utf8) else { throw AIError.invalidJSON }
        do { return try JSONDecoder().decode(T.self, from: data) } catch { throw AIError.invalidJSON }
    }

    // MARK: Course

    func generateCourse(_ request: CourseRequest) async throws -> Course {
        let text = try await chat(system: Prompts.courseSystem,
                                  messages: [Msg(role: "user", content: Prompts.courseUser(request))],
                                  purpose: "course", json: true, maxTokens: 6000, temperature: 0.5)
        let dto = try decode(CourseDTO.self, from: text)
        var course = dto.toCourse(request: request)
        course.generatedBy = displayName
        course.provenance = "Generated by \(modelLabel) on Oracle Cloud Infrastructure Generative AI from your topic, level and goals only. No personal data was sent. An educator should review it before you rely on it."
        guard course.chapters.count >= 1 else { throw AIError.invalidJSON }
        return course
    }

    // MARK: Tutor

    func tutor(_ context: TutorContext, history: [ChatMessage], question: String) async throws -> TutorReply {
        if PrivacyFilter.needsUrgentHumanSupport(question) {
            return TutorReply(text: PrivacyFilter.urgentSupportMessage, sources: ["Safety guidance"])
        }
        var msgs: [Msg] = history.suffix(8).compactMap {
            switch $0.role { case .learner: return Msg(role: "user", content: $0.text)
            case .tutor: return Msg(role: "assistant", content: $0.text)
            case .system: return nil }
        }
        msgs.append(Msg(role: "user", content: question))
        let text = try await chat(system: Prompts.tutorSystem(context), messages: msgs, purpose: "tutor", json: false, maxTokens: 600, temperature: 0.5)
        var sources = ["Chapter \(context.chapter.index + 1): \(context.chapter.title)"]
        if let s = context.currentSection { sources.append("Section \"\(s.heading)\"") }
        sources.append("\(modelLabel) via OCI Generative AI · help level \(context.helpLevel.rawValue)")
        return TutorReply(text: text.trimmingCharacters(in: .whitespacesAndNewlines), sources: sources)
    }

    // MARK: Challenges

    struct EvalDTO: Codable { var reasoningScore: Double?; var feedback: String?; var rubricMet: [String]?; var probe: String? }

    func evaluate(challenge: Challenge, answer: String, reasoning: String, attempt: Int, context: TutorContext) async throws -> Evaluation {
        // Correctness is deterministic on device. The model only judges the reasoning.
        let correct = AnswerChecker.isCorrect(answer, for: challenge)
        let mis = correct ? nil : AnswerChecker.misconception(for: answer, in: challenge)
        let text = try await chat(system: Prompts.evaluateSystem(context),
                                  messages: [Msg(role: "user", content: Prompts.evaluateUser(challenge, answer: answer, reasoning: reasoning, correct: correct, misconception: mis, attempt: attempt))],
                                  purpose: "evaluate", json: true, maxTokens: 500, temperature: 0.2)
        let dto = try decode(EvalDTO.self, from: text)
        let local = AnswerChecker.rubricCoverage(reasoning + " " + answer, rubric: challenge.rubric)
        let met = dto.rubricMet ?? local.met.map(\.idea)
        let missing = challenge.rubric.map(\.idea).filter { !met.contains($0) }
        let score = min(1, max(0, dto.reasoningScore ?? AnswerChecker.reasoningScore(reasoning, rubric: challenge.rubric)))
        return Evaluation(correct: correct, reasoningScore: score,
                          feedback: dto.feedback ?? (correct ? "Correct." : "Not yet. Look at your steps again."),
                          rubricMet: met, rubricMissing: missing, misconception: mis, probe: dto.probe,
                          source: "Answer checked exactly on device. Reasoning feedback by \(modelLabel) (OCI), using the educator-visible rubric.")
    }

    func hint(challenge: Challenge, level: Int, answer: String, reasoning: String, context: TutorContext) async throws -> String {
        let text = try await chat(system: Prompts.hintSystem(context),
                                  messages: [Msg(role: "user", content: Prompts.hintUser(challenge, level: level, answer: answer, reasoning: reasoning))],
                                  purpose: "hint", json: false, maxTokens: 250, temperature: 0.4)
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        // Leak guard: never show a hint that contains the final answer.
        if t.isEmpty || Prompts.leaksAnswer(t, challenge: challenge) {
            return challenge.hints[min(level, challenge.hints.count - 1)]
        }
        return t
    }

    func remediate(chapter: Chapter, topic: String, level: SkillLevel, struggledWith: Challenge, attempts: [ChallengeAttempt], round: Int) async throws -> Remediation {
        let text = try await chat(system: Prompts.remediateSystem,
                                  messages: [Msg(role: "user", content: Prompts.remediateUser(chapter: chapter, topic: topic, level: level, challenge: struggledWith, attempts: attempts, round: round))],
                                  purpose: "remediate", json: true, maxTokens: 2000, temperature: 0.6)
        let dto = try decode(RemediationDTO.self, from: text)
        return dto.toRemediation()
    }

    func triageConcern(_ text: String) async throws -> ConcernTriage {
        if PrivacyFilter.needsUrgentHumanSupport(text) {
            return ConcernTriage(category: "Urgent wellbeing", reply: PrivacyFilter.urgentSupportMessage, urgent: true)
        }
        struct DTO: Codable { var category: String; var reply: String }
        let out = try await chat(system: Prompts.concernSystem, messages: [Msg(role: "user", content: text)], purpose: "concern", json: true, maxTokens: 300)
        let dto = try decode(DTO.self, from: out)
        return ConcernTriage(category: dto.category, reply: dto.reply, urgent: false)
    }

    func summarizeInsights(_ input: InsightSummaryInput) async throws -> String {
        let out = try await chat(system: Prompts.insightsSystem, messages: [Msg(role: "user", content: Prompts.insightsUser(input))], purpose: "insights", json: false, maxTokens: 500)
        return out.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

// MARK: - Classroom

extension GatewayProvider {
    struct FeedbackDTO: Codable {
        struct C: Codable { var quote: String?; var kind: String?; var criterion: String?; var comment: String? }
        struct S: Codable { var criterion: String?; var level: Int?; var rationale: String? }
        var comments: [C]?; var scores: [S]?; var glow: String?; var grow: String?
    }

    func draftEssayFeedback(essay: String, prompt: String, rubric: [RubricCriterion], gradeBand: String, minWords: Int) async throws -> EssayFeedback {
        let text = try await chat(system: Prompts.essayFeedbackSystem,
                                  messages: [Msg(role: "user", content: Prompts.essayFeedbackUser(essay: essay, prompt: prompt, rubric: rubric, gradeBand: gradeBand, minWords: minWords))],
                                  purpose: "feedback", json: true, maxTokens: 2200, temperature: 0.3)
        let dto = try decode(FeedbackDTO.self, from: text)
        func crit(_ name: String?) -> UUID? {
            guard let n = name?.lowercased() else { return nil }
            return rubric.first { $0.name.lowercased() == n || n.contains($0.name.lowercased()) || $0.name.lowercased().contains(n) }?.id
        }
        let raw: [FeedbackComment] = (dto.comments ?? []).compactMap { c in
            guard let q = c.quote, let t = c.comment, !t.isEmpty else { return nil }
            return FeedbackComment(quote: q, kind: CommentKind(rawValue: c.kind ?? "") ?? .suggestion, criterionID: crit(c.criterion), draft: t)
        }
        // Anchor check and tone check happen on device, whatever the model returns.
        let guarded = EssayCoach.guardComments(raw, essay: essay)
        guard !guarded.kept.isEmpty else { throw AIError.invalidJSON }
        let local = EssayCoach.draft(essay: essay, rubric: rubric, minWords: minWords)
        let scores: [CriterionScore] = rubric.map { c in
            if let s = dto.scores?.first(where: { crit($0.criterion) == c.id }), let lvl = s.level {
                return CriterionScore(criterionID: c.id, suggested: min(3, max(0, lvl)), rationale: s.rationale ?? "")
            }
            return local.scores.first { $0.criterionID == c.id } ?? CriterionScore(criterionID: c.id, suggested: 1, rationale: "")
        }
        var fb = EssayFeedback(comments: guarded.kept, scores: scores, glow: dto.glow ?? local.glow, grow: dto.grow ?? local.grow,
                               generatedBy: "\(modelLabel) via OCI Generative AI")
        fb.guardNotes = guarded.notes
        return fb
    }

    struct AssignmentDTO: Codable {
        struct R: Codable { var name: String?; var detail: String?; var levels: [String]? }
        var title: String?; var instructions: String?; var prompt: String?; var minWords: Int?; var standards: [String]?
        var rubric: [R]?; var sections: [SectionDTO]?
    }

    func draftAssignment(_ request: AssignmentRequest) async throws -> AssignmentDraft {
        if request.kind == .quest { return AssignmentStudio.draft(request) }
        let text = try await chat(system: Prompts.assignmentSystem, messages: [Msg(role: "user", content: Prompts.assignmentUser(request))],
                                  purpose: "assignment", json: true, maxTokens: 3500, temperature: 0.5)
        let dto = try decode(AssignmentDTO.self, from: text)
        let fallback = AssignmentStudio.draft(request)
        let rubric: [RubricCriterion] = (dto.rubric ?? []).compactMap { r in
            guard let n = r.name, let lv = r.levels, lv.count == 4 else { return nil }
            return RubricCriterion(name: n, detail: r.detail ?? "", levels: lv)
        }
        let sections = (dto.sections ?? []).map { $0.toSection() }.filter { !$0.body.isEmpty }
        if request.kind == .reading && sections.isEmpty { throw AIError.invalidJSON }
        return AssignmentDraft(title: dto.title ?? fallback.title, instructions: dto.instructions ?? fallback.instructions,
                               prompt: dto.prompt ?? fallback.prompt, rubric: rubric.count >= 3 ? rubric : fallback.rubric,
                               sections: sections, keyTerms: LessonAdapter.Source(sections: sections).keyTerms,
                               standards: dto.standards ?? fallback.standards, minWords: dto.minWords ?? request.minWords,
                               generatedBy: "\(modelLabel) via OCI Generative AI")
    }

    func planLessonStructure(_ sentences: [String], chunkSize: Int) async throws -> LessonAdapter.StructurePlan {
        let text = try await chat(system: Prompts.structureSystem, messages: [Msg(role: "user", content: Prompts.structureUser(sentences, chunkSize: chunkSize))],
                                  purpose: "structure", json: true, maxTokens: 900, temperature: 0.1)
        return try decode(LessonAdapter.StructurePlan.self, from: text)
    }
}

// MARK: - DTOs for model output (lenient: every field optional)

struct CourseDTO: Codable {
    var chapters: [ChapterDTO]?
    func toCourse(request: CourseRequest) -> Course {
        let themes: [LocationTheme] = [.grove, .tower, .castle, .harbor, .observatory]
        let chs = (chapters ?? []).prefix(request.chapterCount).enumerated().map { i, c in c.toChapter(index: i, fallbackTheme: themes[i % themes.count]) }
        return Course(topic: request.topic, level: request.level, stage: request.stage, chapters: Array(chs),
                      generatedBy: "", provenance: "", goals: request.goals)
    }
}

struct NPCDTO: Codable { var name: String?; var role: String?; var greeting: String?; var emoji: String? }

struct ChapterDTO: Codable {
    var title: String?; var summary: String?; var locationName: String?; var theme: String?
    var npc: NPCDTO?; var sections: [SectionDTO]?; var keyIdeas: [String]?; var challenges: [ChallengeDTO]?; var discussionPrompts: [String]?
    func toChapter(index: Int, fallbackTheme: LocationTheme) -> Chapter {
        Chapter(index: index, title: title ?? "Chapter \(index + 1)", summary: summary ?? "",
                locationName: locationName ?? "Location \(index + 1)",
                theme: LocationTheme(rawValue: theme ?? "") ?? fallbackTheme,
                npc: NPC(name: npc?.name ?? "Guide", role: npc?.role ?? "Mentor", greeting: npc?.greeting ?? "Welcome, explorer!", emoji: npc?.emoji ?? "🧙"),
                sections: (sections ?? []).map { $0.toSection() },
                keyIdeas: keyIdeas ?? [],
                challenges: (challenges ?? []).compactMap { $0.toChallenge() },
                discussionPrompts: discussionPrompts ?? [])
    }
}

struct IllustrationDTO: Codable {
    var kind: String?; var caption: String?; var params: [String: Double]?; var labels: [String]?
    func toIllustration() -> Illustration? {
        guard let k = kind, let kind = IllustrationKind(rawValue: k) else {
            if let labels, !labels.isEmpty { return Illustration(kind: .conceptCard, caption: caption ?? "", labels: labels) }
            return nil
        }
        return Illustration(kind: kind, caption: caption ?? "", params: params, labels: labels)
    }
}

struct CheckDTO: Codable {
    var question: String?; var options: [String]?; var correctIndex: Int?; var explanation: String?
    func toCheck() -> QuickCheck? {
        guard let q = question, let o = options, o.count >= 2, let c = correctIndex, o.indices.contains(c) else { return nil }
        return QuickCheck(question: q, options: o, correctIndex: c, explanation: explanation ?? "")
    }
}

struct SectionDTO: Codable {
    var heading: String?; var body: String?; var illustration: IllustrationDTO?; var checkpoint: CheckDTO?
    func toSection(adaptive: Bool = false) -> LessonSection {
        LessonSection(heading: heading ?? "", body: body ?? "", illustration: illustration?.toIllustration(), checkpoint: checkpoint?.toCheck(), isAdaptive: adaptive)
    }
}

struct RubricDTO: Codable { var idea: String?; var keywords: [String]? }

struct ChallengeDTO: Codable {
    var prompt: String?; var answerType: String?; var options: [String]?; var correctAnswer: String?
    var hints: [String]?; var solution: String?; var rubric: [RubricDTO]?; var misconceptions: [String: String]?
    func toChallenge(followUp: Bool = false) -> Challenge? {
        guard let p = prompt, let a = correctAnswer else { return nil }
        let type = AnswerType(rawValue: answerType ?? "") ?? (options?.isEmpty == false ? .multipleChoice : (AnswerChecker.parseNumber(a) != nil ? .numeric : .shortText))
        var hs = hints ?? []
        while hs.count < 3 { hs.append(["List every possible outcome first.", "Which outcomes match what the question asks for?", "Now compare that count with the total."][hs.count]) }
        let rb = (rubric ?? []).compactMap { r -> RubricItem? in
            guard let idea = r.idea else { return nil }
            return RubricItem(idea: idea, keywords: (r.keywords ?? []).map { $0.lowercased() })
        }
        return Challenge(prompt: p, answerType: type, options: options, correctAnswer: a, tolerance: 0.01, hints: Array(hs.prefix(3)),
                         solution: solution ?? "", rubric: rb, misconceptions: misconceptions, isFollowUp: followUp)
    }
}

struct RemediationDTO: Codable {
    var approach: String?; var section: SectionDTO?; var followUp: ChallengeDTO?
    func toRemediation() -> Remediation {
        let fallback = Challenge(prompt: "Explain the main idea of this new page in your own words.", answerType: .shortText, correctAnswer: "", hints: ["Re-read the first paragraph.", "What example did it use?", "Connect the example to the idea."], solution: "", rubric: [])
        return Remediation(approach: approach ?? "A new way to see it",
                           section: section?.toSection(adaptive: true) ?? LessonSection(heading: "Another way to see it", body: "", isAdaptive: true),
                           followUp: followUp?.toChallenge(followUp: true) ?? fallback)
    }
}
